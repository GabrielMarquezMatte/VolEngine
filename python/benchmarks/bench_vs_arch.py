"""Time volengine against arch on the same fits and write the result as a markdown report.

Usage: python python/benchmarks/bench_vs_arch.py [--out PATH] [--repetitions N]
"""

import argparse
import datetime
import os
import platform
import statistics
import subprocess
import time
from collections.abc import Callable
from importlib import metadata
from pathlib import Path
from typing import Literal, NamedTuple

import arch
import numpy as np
import volengine as ve
from arch import arch_model
from numpy.typing import NDArray

ArchDist = Literal["normal", "t", "ged", "skewt"]
ArchVolatility = Literal["GARCH", "EGARCH"]
SERIES_COUNT = 20
LENGTH = 5000
SEED = 7
# The models arch also estimates, with the orders timed for each. arch's volatility process and its asymmetry
# order per ARCH term follow tests/reference/oracle_arch.py.
MODEL_ORDERS = {"sgarch": ((1, 1), (2, 1), (1, 2)), "gjrgarch": ((1, 1),), "egarch": ((1, 1),)}
ARCH_VOLATILITIES: dict[str, tuple[ArchVolatility, int]] = {
    "sgarch": ("GARCH", 0),
    "gjrgarch": ("GARCH", 1),
    "egarch": ("EGARCH", 1),
}
MODEL_NAMES = {"sgarch": "sGARCH", "gjrgarch": "gjrGARCH", "egarch": "eGARCH"}
DISTRIBUTIONS: tuple[tuple[str, ArchDist], ...] = (("norm", "normal"), ("std", "t"), ("ged", "ged"))
# Hansen's skew-t is the same family as sstd, so the log-likelihoods are comparable; the parameterizations differ
# and are not compared.
SKEWED_CASES: tuple[tuple[str, int, int, str, ArchDist], ...] = (("sgarch", 1, 1, "sstd", "skewt"),)
LOGLIK_TOLERANCE = 1e-4


INTRO = """# Python package against arch

Generated by `python/benchmarks/bench_vs_arch.py`. Every number below comes from the one machine listed here;
the ratios compare runs on that machine only and say nothing about another one.

The matched-work rows fit the same simulated series (GARCH(1,1) with Student-t(8) innovations, `default_rng(7)`)
with the same specs: constant mean, sGARCH(p,q), gjrGARCH(1,1) and eGARCH(1,1), each with normal, Student-t or
GED innovations, plus sGARCH(1,1) with skewed Student-t innovations (`sstd` against `arch`'s `skewt`, the same
family with another parameterization). `volengine` runs with `Context(threads=1)` and `var_init="backcast"`, the `arch` convention;
`arch` runs with `rescale=False` and `fit(disp="off")`, one fit after the other. Each timing is the total wall
time of the fits it covers.
"""
NOTES = """
Notes:

- The optimizers differ (L-BFGS in VolEngine, SLSQP in `arch`), so the times include different numbers of
  iterations. The second table shows that both reach the same optimum: the largest relative difference of the
  log-likelihood over the 20 series is below 1e-4 for every spec (the script fails otherwise).
- The `threads=0` row is not matched work: `arch` does not parallelize a fit, so that row measures the batch
  parallelism of VolEngine, not the algorithms. Fits are bit-identical for any thread count.
- The run was not isolated: a normal desktop session, no pinned cores and no fixed frequency.
- Reproduce with `VOLENGINE_LIB=<path to the library> python python/benchmarks/bench_vs_arch.py --out
  docs/performance/python-vs-arch.md` in the `python/.venv` environment.
"""


class Case(NamedTuple):
    model: str
    p: int
    q: int
    dist: str
    arch_dist: ArchDist

    def label(self) -> str:
        return f"{MODEL_NAMES[self.model]}({self.p},{self.q}) {self.dist}"


def cases(model: str) -> list[Case]:
    symmetric = [
        Case(model, p, q, dist, arch_dist) for p, q in MODEL_ORDERS[model] for dist, arch_dist in DISTRIBUTIONS
    ]
    return symmetric + [Case(*case) for case in SKEWED_CASES if case[0] == model]


def simulate() -> NDArray[np.float64]:
    """GARCH(1,1) with Student-t(8) innovations, in percent units, one column per series."""
    rng = np.random.default_rng(SEED)
    shocks = rng.standard_t(8, size=(LENGTH, SERIES_COUNT)) * np.sqrt(6 / 8)
    returns = np.empty_like(shocks)
    variance = np.full(SERIES_COUNT, 0.05 / (1 - 0.08 - 0.90))
    for t in range(LENGTH):
        returns[t] = np.sqrt(variance) * shocks[t]
        variance = 0.05 + 0.08 * returns[t] ** 2 + 0.90 * variance
    return returns


def volengine_fit(case: Case, data: NDArray[np.float64], ctx: ve.Context) -> list[float]:
    spec = ve.Spec(case.model, p=case.p, q=case.q, dist=case.dist)
    fits = ctx.fit([spec], data, options=ve.FitOptions(var_init="backcast"))
    return [fit.loglik for fit in fits[0]]


def arch_fit(case: Case, data: NDArray[np.float64]) -> list[float]:
    vol, asymmetry = ARCH_VOLATILITIES[case.model]
    logliks = []
    for column in data.T:
        model = arch_model(
            column, mean="Constant", vol=vol, p=case.p, o=asymmetry * case.p, q=case.q, dist=case.arch_dist,
            rescale=False,
        )
        logliks.append(float(model.fit(disp="off").loglikelihood))
    return logliks


def timed(work: Callable[[], dict[str, list[float]]], repetitions: int) -> tuple[float, dict[str, list[float]]]:
    seconds = []
    result: dict[str, list[float]] = {}
    for _ in range(repetitions):
        start = time.perf_counter()
        result = work()
        seconds.append(time.perf_counter() - start)
    return statistics.median(seconds), result


def run_volengine(data: NDArray[np.float64], model: str, threads: int) -> dict[str, list[float]]:
    ctx = ve.Context(threads=threads)
    return {case.label(): volengine_fit(case, data, ctx) for case in cases(model)}


def run_arch(data: NDArray[np.float64], model: str) -> dict[str, list[float]]:
    return {case.label(): arch_fit(case, data) for case in cases(model)}


class Timings(NamedTuple):
    """Median wall times in seconds of one model's fits: arch, then volengine with 1 thread and with all cores."""

    arch: float
    one_thread: float
    all_threads: float


def time_model(data: NDArray[np.float64], model: str, repetitions: int) -> tuple[Timings, dict[str, float]]:
    arch_time, arch_logliks = timed(lambda: run_arch(data, model), repetitions)
    one_time, one_logliks = timed(lambda: run_volengine(data, model, 1), repetitions)
    all_time, all_logliks = timed(lambda: run_volengine(data, model, 0), repetitions)
    worst = check_logliks(one_logliks, arch_logliks)
    check_logliks(all_logliks, arch_logliks)
    return Timings(arch_time, one_time, all_time), worst


def relative_difference(ours: list[float], theirs: list[float]) -> float:
    a, b = np.array(ours), np.array(theirs)
    return float(np.max(np.abs(a - b) / np.abs(b)))


def check_logliks(ours: dict[str, list[float]], theirs: dict[str, list[float]]) -> dict[str, float]:
    worst = {label: relative_difference(ours[label], theirs[label]) for label in ours}
    outside = {label: value for label, value in worst.items() if not value <= LOGLIK_TOLERANCE}
    if outside:
        raise RuntimeError(f"log-likelihoods differ by more than {LOGLIK_TOLERANCE} (relative): {outside}")
    return worst


def powershell(query: str) -> str:
    done = subprocess.run(["powershell", "-NoProfile", "-Command", query], capture_output=True, text=True, check=True)
    return done.stdout.strip()


def machine_description() -> str:
    if platform.system() != "Windows":
        return f"{platform.processor() or platform.machine()}, {os.cpu_count()} hardware threads, {platform.platform()}"
    name = powershell("(Get-CimInstance Win32_Processor).Name")
    cores = powershell("(Get-CimInstance Win32_Processor).NumberOfCores")
    memory = int(powershell("(Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory")) / 2**30
    return f"{name}, {cores} cores, {os.cpu_count()} hardware threads, {memory:.0f} GiB RAM, {platform.platform()}"


def fit_count(model: str) -> int:
    return SERIES_COUNT * len(cases(model))


def model_rows(timings: dict[str, Timings]) -> list[str]:
    lines = [
        "",
        "| Model (matched work) | Fits | arch (s) | volengine, threads=1 (s) | Relative to arch on this machine |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for model, t in timings.items():
        name, ratio = MODEL_NAMES[model], t.arch / t.one_thread
        lines.append(f"| {name} | {fit_count(model)} | {t.arch:.2f} | {t.one_thread:.2f} | {ratio:.2f}x |")
    return lines


def report(rows: dict[str, float], timings: dict[str, Timings], repetitions: int) -> str:
    arch_time = sum(t.arch for t in timings.values())
    one_thread = sum(t.one_thread for t in timings.values())
    all_threads = sum(t.all_threads for t in timings.values())
    fits = sum(fit_count(model) for model in timings)
    lines = [
        INTRO,
        f"- Machine: {machine_description()}",
        f"- Versions: volengine {metadata.version('volengine')}, arch {arch.__version__}, "
        f"numpy {np.__version__}, Python {platform.python_version()}",
        f"- Date: {datetime.date.today().isoformat()}",
        f"- Work: {SERIES_COUNT} series of {LENGTH} observations, {len(rows)} specs, "
        f"{SERIES_COUNT * len(rows)} fits per library; median wall time of {repetitions} repetitions.",
        "",
        "| Run | Wall time (s) | Fits per second | Relative to arch on this machine |",
        "| --- | ---: | ---: | ---: |",
    ]
    for name, seconds in (
        ("arch, sequential (matched work)", arch_time),
        ("volengine, threads=1 (matched work)", one_thread),
        ("volengine, threads=0 (all cores; not matched work)", all_threads),
    ):
        lines.append(f"| {name} | {seconds:.2f} | {fits / seconds:.1f} | {arch_time / seconds:.2f}x |")
    lines += model_rows(timings)
    lines += ["", "| Spec | Worst relative loglik difference over the series |", "| --- | ---: |"]
    lines += [f"| {label} | {value:.1e} |" for label, value in rows.items()]
    return "\n".join(lines) + "\n" + NOTES


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path)
    parser.add_argument("--repetitions", type=int, default=5)
    args = parser.parse_args()
    data = simulate()
    timings: dict[str, Timings] = {}
    worst: dict[str, float] = {}
    for model in MODEL_ORDERS:
        timings[model], model_worst = time_model(data, model, args.repetitions)
        worst.update(model_worst)
    text = report(worst, timings, args.repetitions)
    print(text)
    if args.out is not None:
        args.out.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
